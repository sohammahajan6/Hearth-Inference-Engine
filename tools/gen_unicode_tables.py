"""Generate src/tokenizer/unicode_tables.cpp from the pinned Unicode Character
Database.

The Llama-3 pre-tokenizer needs three character classes:
    \\p{L}  general category L*      (UnicodeData.txt)
    \\p{N}  general category N*      (UnicodeData.txt)
    \\s     property White_Space     (PropList.txt)

Usage:
    .venv\\Scripts\\python -I tools\\gen_unicode_tables.py [--ucd DIR] [--out FILE]
    ... --check             exit 1 if FILE differs from what would be generated
    ... --compare-llama F   also compare llama.cpp's flag table F (unicode-data.cpp)
"""

import argparse
import hashlib
import pathlib
import re
import sys

MAX = 0x110000
ROOT = pathlib.Path(__file__).resolve().parent.parent


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_categories(path):
    """General category of every codepoint ('Cn' when unassigned), and the simple lowercase map."""
    cat = ["Cn"] * MAX
    lower = {}
    first = None
    for line in path.read_text(encoding="utf-8").splitlines():
        f = line.split(";")
        cpt, name, c = int(f[0], 16), f[1], f[2]
        if f[13]:
            lower[cpt] = int(f[13], 16)
        if name.endswith(", First>"):
            first = cpt
            continue
        if name.endswith(", Last>"):
            for x in range(first, cpt):
                cat[x] = c
        cat[cpt] = c
    return cat, lower


def read_white_space(path):
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*White_Space\b", line)
        if m:
            a = int(m.group(1), 16)
            b = int(m.group(2), 16) if m.group(2) else a
            out.extend(range(a, b + 1))
    return sorted(out)


def ranges(predicate):
    out, start = [], None
    for c in range(MAX + 1):
        inside = c < MAX and predicate(c)
        if inside and start is None:
            start = c
        elif not inside and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def render(version, hashes, letters, numbers, white):
    def table(name, rs):
        body = "\n".join(f"    {{0x{a:06X}, 0x{b:06X}}}," for a, b in rs)
        return f"const Range {name}[] = {{\n{body}\n}};\nconst std::size_t {name}Count = {len(rs)};\n"

    ws = "\n".join(f"    0x{c:06X}," for c in white)
    return f"""// Generated by tools/gen_unicode_tables.py from the Unicode Character Database
// {version}. Do not edit; regenerate instead.
//   UnicodeData.txt sha256 {hashes[0]}
//   PropList.txt    sha256 {hashes[1]}
// Ranges are inclusive and sorted. Licensed under the Unicode License V3
// (THIRD_PARTY_NOTICES.md).
#include "tokenizer/unicode_tables.h"

// clang-format off
namespace hearth::tokenizer::unicode {{

// \\p{{L}}: general category Lu, Ll, Lt, Lm, Lo.
{table("kLetters", letters)}
// \\p{{N}}: general category Nd, Nl, No.
{table("kNumbers", numbers)}
// \\s: property White_Space.
const char32_t kWhiteSpace[] = {{
{ws}
}};
const std::size_t kWhiteSpaceCount = {len(white)};

}}  // namespace hearth::tokenizer::unicode
// clang-format on
"""


def compare_llama(path, cat):
    """The comparison of docs/adr/0008: letter and number classes against llama.cpp's flags."""
    text = path.read_text(encoding="utf-8")
    body = text[text.index("unicode_ranges_flags"):]
    body = body[:body.index("};")]
    rs = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-F]+), 0x([0-9A-F]+)\}", body)]
    differ = 0
    for (start, flags), (nxt, _) in zip(rs, rs[1:] + [(MAX, 0)]):
        for c in range(start, min(nxt, MAX)):
            ours = (0x0004 if cat[c][0] == "L" else 0) | (0x0002 if cat[c][0] == "N" else 0)
            if ours != flags & 0x0006:
                differ += 1
    return differ


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd", default=str(ROOT / "third_party" / "unicode" / "15.1.0"))
    ap.add_argument("--out", default=str(ROOT / "src" / "tokenizer" / "unicode_tables.cpp"))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--compare-llama")
    args = ap.parse_args()
    ucd = pathlib.Path(args.ucd)
    data, props = ucd / "UnicodeData.txt", ucd / "PropList.txt"
    version = ucd.name
    cat, lower = read_categories(data)
    # The pre-tokenizer folds case only to recognise the contractions 's 't 're
    # 've 'm 'll 'd. Under the simple lowercase mapping, only ASCII capitals map
    # onto those letters, so ASCII folding is exact.
    for c, low in lower.items():
        if chr(low) in "stmdrevl" and not ("A" <= chr(c) <= "Z"):
            raise SystemExit(f"U+{c:04X} lowercases to '{chr(low)}': ASCII case folding would be wrong")
    letters = ranges(lambda c: cat[c][0] == "L")
    numbers = ranges(lambda c: cat[c][0] == "N")
    white = read_white_space(props)
    text = render(version, (sha256(data), sha256(props)), letters, numbers, white)
    out = pathlib.Path(args.out)
    if args.compare_llama:
        n = compare_llama(pathlib.Path(args.compare_llama), cat)
        print(f"letter/number classes differing from {args.compare_llama}: {n} codepoints")
        if n:
            return 1
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} is out of date: run tools/gen_unicode_tables.py")
            return 1
        print(f"{out} is up to date ({len(letters)} letter ranges, {len(numbers)} number ranges, "
              f"{len(white)} whitespace)")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(letters)} letter ranges, {len(numbers)} number ranges, {len(white)} whitespace")
    return 0


if __name__ == "__main__":
    sys.exit(main())
