"""Write requirements.txt with sha256 hashes for every pinned package.

Input: `pip freeze` output (name==version lines) on stdin.
Output: requirements.txt lines with --hash entries for the wheels that can
install on this project's only Python target (CPython 3.12, win_amd64).

Hashes come from PyPI's JSON API (the digests PyPI publishes for each file),
so `pip install --require-hashes` refuses any file that differs.

Usage:
    .venv\\Scripts\\python -m pip freeze | python -I tools/pin_requirements.py > requirements.txt
"""

import json
import sys
import urllib.request


def wheel_fits(filename: str) -> bool:
    if not filename.endswith(".whl"):
        return False
    # name-version(-build)?-pyver-abi-platform.whl
    parts = filename[:-4].split("-")
    pyver, abi, plat = parts[-3], parts[-2], parts[-1]
    if plat == "any":
        return True
    if plat != "win_amd64":
        return False
    return "cp312" in pyver.split(".") or abi == "abi3"


def main() -> int:
    out = [
        "# Generated by tools/pin_requirements.py from `pip freeze`. Do not edit by hand.",
        "# Install with: pip install --require-hashes --only-binary=:all: -r requirements.txt",
    ]
    for raw in sys.stdin.read().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        name, _, version = line.partition("==")
        if not version:
            print(f"unpinned line, refusing: {line}", file=sys.stderr)
            return 1
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        with urllib.request.urlopen(url, timeout=30) as resp:
            info = json.load(resp)
        hashes = sorted(
            f["digests"]["sha256"] for f in info["urls"] if wheel_fits(f["filename"])
        )
        if not hashes:
            print(f"no compatible wheel for {name}=={version}", file=sys.stderr)
            return 1
        out.append(f"{name}=={version} \\")
        out.extend(f"    --hash=sha256:{h} \\" for h in hashes[:-1])
        out.append(f"    --hash=sha256:{hashes[-1]}")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
